def build_placement_verdict_prompt(
    ad_name: str,
    placement_mode_label: str,
    rows: list,
    verdict: dict,
    objective_label: str = None,
    lang: str = "ru",
) -> tuple:
    """Людський висновок поверх порахованої по цифрах розбивки по плейсментах (Reels/Stories/
    Стрічка/Audience Network тощо) для ОДНОГО оголошення — той самий патерн, що
    build_audience_verdict_prompt/build_creative_verdict_prompt вище, але з окремим наголосом на
    Advantage+ (авто-плейсменти): 0 витрат на плейсменті там — це вибір алгоритму, а не "поганий"
    плейсмент, і про це треба сказати прямо, інакше власник акаунта сприймає порожні рядки як
    провал плейсменту."""
    system_prompt = (
        "Ти — таргетолог Meta Ads, що пояснює власнику акаунта, де реально дешевше виходить "
        "результат по плейсментах (Reels/Stories/Стрічка/Audience Network тощо) для ОДНОГО "
        "оголошення, і чому бюджет розподілився саме так.\n\n"
        + HONESTY_AND_ACTION_RULES + "\n\n"
        + VOLUME_HONESTY_RULES + "\n\n"
        "Додаткові правила саме для цієї задачі:\n"
        "- Якщо плейсменти в режимі «Авто» (Advantage+/розширені) — ОБОВ'ЯЗКОВО поясни, що це "
        "Meta сама розподіляє покази туди, де їй зараз дешевше вийшов результат, і що 0 витрат "
        "на якомусь плейсменті — це НЕ ознака того, що він «поганий», а ознака того, що алгоритм "
        "визнав інший плейсмент вигіднішим по ціні результату. НЕ радь вручну вимикати «погані» "
        "плейсменти в авто-режимі — там і так майже не було показів, вимикати нічого.\n"
        "- Якщо хочеш запропонувати перевірити конкретний плейсмент окремо — запропонуй створити "
        "ОКРЕМУ групу оголошень (adset) тільки з цим плейсментом і порівняти ціну результата, але "
        "чесно попередь: ручне дроблення по плейсментах майже завжди виходить дорожче за спільну "
        "автоматичну оптимізацію (алгоритм втрачає обсяг показів і гнучкість перерозподілу "
        "бюджету між плейсментами) — тому це має сенс лише як короткий свідомий тест, а не "
        "постійна структура кампанії.\n"
        "- 3-5 речень, без вступів: який плейсмент дешевший по ціні результата, куди ллється "
        "бюджет і чому, що робити далі.\n\n"
        + _lang_instruction(lang)
    )

    def _row_line(r: dict) -> str:
        m = r.get("metrics") or {}
        res = r.get("result") or {}
        spend = m.get("spend")
        if not spend:
            return f"- {r['label']}: витрат за період немає (0 показів або мінімальний охоплення)"
        parts = [f"витрати {spend}"]
        if res.get("value") is not None:
            parts.append(f"{res.get('label')}={res.get('value')}")
        else:
            parts.append("результат: немає даних" + (f" ({res['note']})" if res.get("note") else ""))
        if res.get("cost_per_result") is not None:
            parts.append(f"ціна результата {res.get('cost_per_result')}")
        if m.get("ctr") is not None:
            parts.append(f"CTR {m.get('ctr')}")
        if m.get("cpm") is not None:
            parts.append(f"CPM {m.get('cpm')}")
        return f"- {r['label']}: " + ", ".join(parts)

    sorted_rows = sorted(rows, key=lambda r: (r.get("metrics") or {}).get("spend") or 0, reverse=True)
    rows_text = "\n".join(_row_line(r) for r in sorted_rows) or "даних по плейсментах немає"

    if verdict.get("available"):
        best, worst = verdict["best"], verdict["worst"]
        verdict_line = f"дешевше всього «{best['label']}», дорожче всього «{worst['label']}»"
        if verdict.get("diff_pct") is not None:
            verdict_line += f", різниця {verdict['diff_pct']}%"
        if verdict.get("note"):
            verdict_line += f". Примітка: {verdict['note']}"
    else:
        verdict_line = f"порівняти неможливо: {verdict.get('note') or 'недостатньо даних'}"

    user_message = (
        f"Оголошення: «{ad_name or 'без назви'}»\n"
        f"Ціль кампанії: {objective_label or 'немає даних'}\n"
        f"Режим плейсментів: {placement_mode_label}\n\n"
        f"Дані по плейсментах:\n{rows_text}\n\n"
        f"Порахований по цифрах вердикт: {verdict_line}"
    )
    return system_prompt, user_message


