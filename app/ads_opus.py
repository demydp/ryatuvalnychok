"""
Промпты и вызов Opus для рекламного модуля: короткий человеческий разбор "аудитория та или
не та" (привязан к вердикту из ads_audience.py) и финальные рекомендации 4d ("мозг таргетолога").
Тот же паттерн вызова, что в app/script_generator.py — client.messages.create с system+user.
"""
import re

import anthropic

from app.ai_standard import HONESTY_AND_ACTION_RULES, VOLUME_HONESTY_RULES

OPUS_MODEL_ID = "claude-opus-4-8"

# Промпты ниже написаны по-русски (сама инструкция Claude), но ОТВЕТ Opus показывается
# пользователю как есть — поэтому язык ответа должен совпадать с языком интерфейса,
# иначе UK-режим всегда получал бы русский текст от Opus. См. app/routes/ads.py,
# где current_lang() передаётся в build_*_prompt().
_RESPONSE_LANG_INSTRUCTION = {
    "ru": "Ответь на русском языке.",
    "uk": "Дай відповідь українською мовою.",
}


def _lang_instruction(lang: str) -> str:
    return _RESPONSE_LANG_INSTRUCTION.get(lang, _RESPONSE_LANG_INSTRUCTION["ru"])


def call_opus(api_key: str, system_prompt: str, user_message: str, max_tokens: int = 500) -> str:
    client = anthropic.Anthropic(api_key=api_key)
    response = client.messages.create(
        model=OPUS_MODEL_ID,
        max_tokens=max_tokens,
        system=system_prompt,
        messages=[{"role": "user", "content": user_message}],
    )
    return "".join(b.text for b in response.content if b.type == "text").strip()


def format_organic_audience(organic_audience: dict) -> str:
    by_age = organic_audience.get("by_age") or {}
    by_gender = organic_audience.get("by_gender") or {}
    total_age = sum(by_age.values()) or 1
    total_gender = sum(by_gender.values()) or 1
    age_parts = sorted(by_age.items(), key=lambda kv: -kv[1])[:4]
    gender_parts = sorted(by_gender.items(), key=lambda kv: -kv[1])
    age_line = ", ".join(f"{age} — {round(v / total_age * 100)}%" for age, v in age_parts)
    gender_line = ", ".join(f"{g} — {round(v / total_gender * 100)}%" for g, v in gender_parts)
    return f"возраст: {age_line or 'нет данных'}; пол: {gender_line or 'нет данных'}"


